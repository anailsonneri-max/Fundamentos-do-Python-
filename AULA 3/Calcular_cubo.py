# leitura do número real
numero = float(input('Digite um número real: '))
print()
cubo = numero ** 3 # cálculo do cubo
print()
print(f'O cubo de {numero} é {cubo}')


# a função input () recebe o texto digitado pelo usuário
# o float() converte esse valor para um número real( com casas decimais)
# Cálculo de potência o operador ** eleva o número á potência que neste caso é o 3
# o 'f' antes das aspas cria uma string formatada
# as chaves funciona como espaço reservados dentro da frase, entende que deve substituir
#                                                           o que está dentro delas pelo

