# leitura de numeros inteiros ( concatenação)
numero1 = int(input('Digite o primeiro número inteiro: '))
numero2 = int(input('Digite o segundo número inteiro: '))
resultado = str(numero1) + str(numero2)
print('Número concatenados:', resultado)

# o comando int(input(.....)) garante que o usuário digitou um número inteiro
# a conversão para testo é (str) se usar o sinal de + entre numeros, vão somar.
# para juntar um do lado do outro prescisa concatenar usanto (str)
# o print se o resultado estiver no singular o numero também

